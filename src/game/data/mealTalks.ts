const NPC_WHO = new Set<string>(['sgt', 'senior', 'buddy', 'junior', 'junior2', 'lt', 'sgm', 'cpt']);
/** 그날 부대에 없는 사람의 대사는 뺀다 */
const onlyPresent = (lines: Line[], present: NpcId[]) => lines.filter((l) => !NPC_WHO.has(l.who) || present.includes(l.who as NpcId));

/** 그 끼니의 밥상 대화 (대본이 없거나, 말할 사람이 아무도 없으면 지문 한 줄) */
export function mealTalk(day: number, meal: 'lunch' | 'dinner', present: NpcId[]): Line[] {
  const lines = onlyPresent(TALKS[`${day}-${meal}`] ?? [], present);
  return lines.length ? lines : [narr('말없이 숟가락만 움직인다. 식당 안의 숟가락 소리가 이상할 만큼 고르다.')];
}
/** 분대장으로서 먹는 아침의 대화 */
export function breakfastTalk(day: number, present: NpcId[]): Line[] {
  const lines = onlyPresent(BREAKFASTS[Math.max(0, day - 7) % BREAKFASTS.length], present);
  return lines.length ? lines : [narr('분대원들과 둘러앉아 아침을 먹었다.')];
}
