/** 지금 보러 갈 장면: 그날까지 열린 것 중 아직 안 본 것, 늦게 열린 것부터. 없으면 null */
export function nextWander(day: number, flags: Record<string, boolean>): Wander | null {
  const open = WANDERS.filter((w) => w.from <= day && !seen(w, flags));
  if (!open.length) return null;
  return open.reduce((a, b) => (b.from > a.from ? b : a));
}

/** 그 자리에서 볼 수 있는 장면 (아직 안 본 것) */
export function wanderAt(spot: string, day: number, flags: Record<string, boolean>): Wander | null {
  return WANDERS.find((w) => w.spot === spot && w.from <= day && !seen(w, flags)) ?? null;
}

/** 그 자리에 지금 계급으로 풀 수 있는, 아직 안 푼 짬짬이 퍼즐이 있는지 */
export function quickOpenAt(spot: string, day: number, solved: (id: string) => boolean): boolean {
  const q = QUICK_SPOTS[spot];
  const def = q ? PUZZLES[q.puzzle] : undefined;
  return !!q && !!def && !solved(q.puzzle) && rankIdxForDay(day) >= QUICK_LEVELS[def.level ?? 1].rank;
}

/** 지금 혼자 가 보기로 한 곳이 퍼즐이 아니라 걷다 마주치는 장면인지 (상단 안내 문구용) */
export function soloWalk(s: { solo: string | null; day: number; flags: Record<string, boolean>; puzzles: Record<string, { solved?: boolean } | undefined> }): boolean {
  return !!s.solo && !quickOpenAt(s.solo, s.day, (id) => !!s.puzzles[id]?.solved) && !!wanderAt(s.solo, s.day, s.flags);
}
