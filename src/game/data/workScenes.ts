/**
 * 일과 장면: 오전·오후 일과 집합 뒤에 나오는 짧은 이야기.
 * 일과 자체는 조작하지 않는다. 그 시간에 분대원들과 나눈 말과, 조금씩 어긋나는 부대의 모습을 보여 준다.
 * - 키: `${일차}-${am|pm}` (1~11일차)
 * - `{work}`는 그날 일과 이름(군별로 다르다)으로 바뀐다
 * - 등장인물은 그날 부대에 있는 사람만: 분대장 1~3일차 · 맞선임 1~6일차 · 후임 4일차~ · 막내 7일차~
 */
export interface WorkScene {
  lines: Line[];
  choices?: Choice[];
}

const say = (who: LineWho, text: string): Line => ({ who, text });
const narr = (text: string) => say('narr', text);
const me = (text: string) => say('me', text);

