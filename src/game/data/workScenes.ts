/** 그날 그 시간대의 일과 장면 (없으면 null → 지문 한 줄로 지나간다) */
export function workScene(day: number, slot: 'am' | 'pm', work: string): WorkScene | null {
  const sc = WORK_SCENES[`${day}-${slot}`];
  if (!sc) return null;
  const put = (l: Line): Line => ({ ...l, text: l.text.replace(/\{work\}/g, work) });
  return { lines: sc.lines.map(put), choices: sc.choices?.map((c) => ({ ...c, reply: c.reply.map(put) })) };
}

