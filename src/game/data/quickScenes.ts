import type { Line, LineWho, NpcId } from '../types';

/**
 * 🧩 짬짬이 퍼즐마다의 상황 (data/puzzles.ts QUICK_SPOTS · PUZZLES의 Q-xx).
 * 퍼즐은 그 자리에서 누군가 실제로 겪고 있는 일이다: 문제를 안은 포켓몬이 상황을 꺼내고(intro),
 * 내가 풀어 주면 그 포켓몬이 한마디 한다(outro).
 * - 키는 장소 ID (QUICK_SPOTS와 같다)
 * - host: 상황을 꺼내는 쪽. 'x:<엑스트라 id>' 또는 주요 인물(NpcId). who: 'npc' 줄은 host의 말이다
 * - 글 안의 {x:<엑스트라 id>}는 그날 그 엑스트라의 이름으로 바뀐다 (군마다 이름이 다른 사람)
 * - 장소에서 살펴보기로 열든, host에게 말을 걸어 열든, 혼자 실마리를 찾아 왔든 같은 장면이 나온다
 * - 답을 미리 말하지 않는다 (지문의 숫자를 다시 읽어 주는 정도까지만)
 */
export interface QuickScene {
  host: string;
  intro: Line[];
  outro: Line[];
}

