/** 이 엑스트라가 상황을 꺼내는 짬짬이 퍼즐의 장소 (없으면 null) */
export function quickSpotOfHost(extraId: string): string | null {
  for (const [spot, sc] of Object.entries(QUICK_SCENES)) if (sc.host === `x:${extraId}`) return spot;
  return null;
}

/** host가 주요 인물이면 그 id */
export const hostNpc = (host: string): NpcId | null => (host.startsWith('x:') ? null : (host as NpcId));

/** {x:<id>} 자리에 그날 그 엑스트라의 이름을 넣는다 */
export function fillExtraNames(lines: Line[], nameOf: (id: string) => string | undefined): Line[] {
  return lines.map((l) => ({ ...l, text: l.text.replace(/\{x:(\w+)\}/g, (_m, id: string) => nameOf(id) ?? '옆 사람') }));
}
