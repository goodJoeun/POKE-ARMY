export interface PuzzleDef {
  id: string;
  /** 붙어 있는 스토리 미션 */
  mission: string;
  title: string;
  /** 지문 (문단 단위) */
  prompt: string[];
  /** 지문 옆에 그리는 그림 */
  art?: 'mirrorClock' | 'pendulum' | 'digital' | 'yard';
  /** digital 그림에 띄울 숫자 */
  artText?: string;
  /**
   * 지문에 나오는 포켓몬 삽화 (art가 없는 퍼즐만). sprite = manifest 키, count = 같은 포켓몬 여러 마리.
   * 한 마리면 크게, 여럿이면 작은 도트로 모아 세운다.
   */
  cast?: { sprite: string; count?: number }[];
  /** 제한 시간 (실패가 있는 자리에서만 쓴다) */
  timeLimitMs?: number;
  /** 한 번 틀리면 바로 실패 (실패가 있는 자리에서만 쓴다) */
  oneShot?: boolean;
  /** 지문 아래 쪽지처럼 보여 주는 글 (메모 · 누군가의 말) */
  notes?: string[];
  input: PuzzleInput;
  /** 힌트 3단계: 방향 → 핵심 → 거의 정답 */
  hints: [string, string, string];
  /** 정답을 맞혔을 때 한 줄 */
  solvedText: string;
  /** 별 조각이 걸린 관문 퍼즐 */
  gate?: boolean;
  /** 힌트가 없는 퍼즐. 힌트 자리에 이 문장을 보여 준다 */
  noHints?: string;
  /** 짬짬이 퍼즐의 난이도 */
  level?: QuickLevel;
}

